#!/bin/sh
# Makes the generated shader variants in vita/shaders from their
# sources (one source of truth each, a #define selecting the variant):
#   nativepsp_raw_plain_v.cg        nativepsp_raw_v.cg + RAW_PLAIN (no skinning, no lights)
#   nativepsp_textured_fix_f.cg     nativepsp_textured_f.cg + BLEND_FIX (grey FIX B blending)
#   nativepsp_textured_test_fix_f.cg nativepsp_textured_test_f.cg + BLEND_FIX
# Run after changing a source, then compile the shaders on the Vita
# (README.md "Shaders").
cd "$(dirname "$0")/../vita/shaders"
variant() {  # <source stem> <define> <output stem>
  {
    echo "// GENERATED by scripts/shader-variants.sh from $1.cg: do not edit."
    echo "#define $2 1"
    cat "$1.cg"
  } > "$3.cg"
  echo "wrote $3.cg"
}
variant nativepsp_raw_v RAW_PLAIN nativepsp_raw_plain_v
variant nativepsp_textured_f BLEND_FIX nativepsp_textured_fix_f
variant nativepsp_textured_test_f BLEND_FIX nativepsp_textured_test_fix_f
