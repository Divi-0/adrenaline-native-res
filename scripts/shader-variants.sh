#!/bin/sh
# Makes the generated shader variants in vita/shaders from their
# sources (one source of truth each, a #define selecting the variant):
#   nativeres_raw_plain_v.cg        nativeres_raw_v.cg + RAW_PLAIN (one bone, no lights)
#   nativeres_raw_plain4_v.cg       nativeres_raw_v.cg + RAW_PLAIN4 (up to four bones, no lights)
#   nativeres_raw_lit1_v.cg         nativeres_raw_v.cg + RAW_LIT1 (one bone, lights)
#   nativeres_raw_lit4_v.cg         nativeres_raw_v.cg + RAW_LIT4 (up to four bones, lights)
#   nativeres_raw_lit1flat_v.cg     nativeres_raw_v.cg + RAW_LIT1_FLAT (RAW_LIT1, coefficient <= 0, 3 lights)
#   nativeres_raw_lit4flat_v.cg     nativeres_raw_v.cg + RAW_LIT4_FLAT (RAW_LIT4, coefficient <= 0, 3 lights)
#   nativeres_raw_lit1point_v.cg    nativeres_raw_v.cg + RAW_LIT1_POINT (RAW_LIT1 with point lights; generic colour only)
#   nativeres_raw_lit4point_v.cg    nativeres_raw_v.cg + RAW_LIT4_POINT (RAW_LIT4 with point lights; generic colour only)
#   nativeres_raw_<variant>_<colour>_v.cg  each of these six + RAW_COLOR_<colour> (none, 5650,
#                                   5551, 4444, 8888: the vertex colour format fixed)
#   nativeres_textured_fix_f.cg     nativeres_textured_f.cg + BLEND_FIX (grey FIX B blending)
#   nativeres_textured_test_fix_f.cg nativeres_textured_test_f.cg + BLEND_FIX
#   nativeres_textured_ge_f.cg      nativeres_textured_f.cg + GE_FILTER (the GE's bilinear filter,
#                                   draws reading our targets)
#   nativeres_textured_fix_ge_f.cg  nativeres_textured_f.cg + BLEND_FIX GE_FILTER
#   nativeres_color_read_f.cg       nativeres_textured_read_f.cg + UNTEXTURED (16-bit targets, untextured)
#   nativeres_textured_read_<way>_f.cg, nativeres_color_read_<way>_f.cg
#                                   the same + READ_NORMAL / READ_ADD / READ_OFF, the normalkeep and
#                                   addkeep ones also READ_KEEP_ALPHA, the textured ...test ones also
#                                   READ_TEST (fast 5551 variants, programs.rs read_gxp); each
#                                   of these also as ...dither_f with READ_DITHER
#   nativeres_textured_read_<way>565[test][dither]_f.cg, nativeres_color_read_<way>565[dither]_f.cg
#                                   the fast ways for 565 targets (READ_565), with invisible565;
#                                   textured also ..565nofog.. (NO_FOG: draws without fog)
#   nativeres_color_read_subtract565_f.cg
#                                   UNTEXTURED READ_SUBTRACT READ_565 (one, one, reverse subtract)
#   nativeres_color_read_invisible[keep][dither]_f.cg
#                                   UNTEXTURED READ_INVISIBLE (normal blends of alpha 0)
#   nativeres_textured_read_<way>widekeep[nofog][test]_f.cg, nativeres_color_read_<way>widekeep_f.cg
#                                   8-bit targets (READ_WIDE READ_KEEP_ALPHA: the normal / add blend as
#                                   the GE does, no cut; frame read)
# Run after changing a source, then compile the shaders on the Vita
# (README.md "Shaders").
cd "$(dirname "$0")/../vita/shaders"
variant() {  # <source stem> "<define> ..." <output stem>
  {
    echo "// GENERATED by scripts/shader-variants.sh from $1.cg: do not edit."
    for define in $2; do echo "#define $define 1"; done
    cat "$1.cg"
  } > "$3.cg"
  echo "wrote $3.cg"
}
variant nativeres_raw_v RAW_PLAIN nativeres_raw_plain_v
variant nativeres_raw_v RAW_PLAIN4 nativeres_raw_plain4_v
variant nativeres_raw_v RAW_LIT1 nativeres_raw_lit1_v
variant nativeres_raw_v RAW_LIT4 nativeres_raw_lit4_v
variant nativeres_raw_v RAW_LIT1_FLAT nativeres_raw_lit1flat_v
variant nativeres_raw_v RAW_LIT4_FLAT nativeres_raw_lit4flat_v
variant nativeres_raw_v RAW_LIT1_POINT nativeres_raw_lit1point_v
variant nativeres_raw_v RAW_LIT4_POINT nativeres_raw_lit4point_v
# Each of them with a fixed vertex colour format (RAW_COLOR_*).
for v in PLAIN:plain PLAIN4:plain4 LIT1:lit1 LIT4:lit4 LIT1_FLAT:lit1flat LIT4_FLAT:lit4flat; do
  for color in NONE 5650 5551 4444 8888; do
    lower=$(echo $color | tr A-Z a-z)
    variant nativeres_raw_v "RAW_${v%%:*} RAW_COLOR_$color" nativeres_raw_${v#*:}_${lower}_v
  done
done
variant nativeres_textured_f BLEND_FIX nativeres_textured_fix_f
variant nativeres_textured_f GE_FILTER nativeres_textured_ge_f
variant nativeres_textured_f "BLEND_FIX GE_FILTER" nativeres_textured_fix_ge_f
variant nativeres_textured_test_f BLEND_FIX nativeres_textured_test_fix_f
variant nativeres_textured_read_f UNTEXTURED nativeres_color_read_f
for dither in "" dither; do
  DITHER=$([ -n "$dither" ] && echo READ_DITHER)
  for way in normal add off; do
    WAY=READ_$(echo $way | tr a-z A-Z)
    variant nativeres_textured_read_f "$WAY $DITHER" nativeres_textured_read_${way}${dither}_f
    variant nativeres_textured_read_f "$WAY READ_TEST $DITHER" nativeres_textured_read_${way}test${dither}_f
    variant nativeres_textured_read_f "UNTEXTURED $WAY $DITHER" nativeres_color_read_${way}${dither}_f
    # READ_OFF keeps the alpha by GXM's colour mask: no keep variant.
    if [ $way != off ]; then
      variant nativeres_textured_read_f "$WAY READ_KEEP_ALPHA $DITHER" nativeres_textured_read_${way}keep${dither}_f
      variant nativeres_textured_read_f "$WAY READ_KEEP_ALPHA READ_TEST $DITHER" nativeres_textured_read_${way}keeptest${dither}_f
      variant nativeres_textured_read_f "UNTEXTURED $WAY READ_KEEP_ALPHA $DITHER" nativeres_color_read_${way}keep${dither}_f
    fi
  done
  # 565 targets (READ_565: green cut to 6 bits; no keep-alpha ones).
  for way in normal add off; do
    WAY=READ_$(echo $way | tr a-z A-Z)
    variant nativeres_textured_read_f "$WAY READ_565 $DITHER" nativeres_textured_read_${way}565${dither}_f
    variant nativeres_textured_read_f "$WAY READ_565 READ_TEST $DITHER" nativeres_textured_read_${way}565test${dither}_f
    variant nativeres_textured_read_f "UNTEXTURED $WAY READ_565 $DITHER" nativeres_color_read_${way}565${dither}_f
    # Draws without fog (NO_FOG: the fog part left out, ~14 instructions).
    variant nativeres_textured_read_f "$WAY READ_565 NO_FOG $DITHER" nativeres_textured_read_${way}565nofog${dither}_f
    variant nativeres_textured_read_f "$WAY READ_565 NO_FOG READ_TEST $DITHER" nativeres_textured_read_${way}565nofogtest${dither}_f
  done
  variant nativeres_textured_read_f "UNTEXTURED READ_INVISIBLE READ_565 $DITHER" nativeres_color_read_invisible565${dither}_f
  # One, one, reverse subtract: untextured 565, undithered only (ReadWay::Subtract).
  if [ -z "$dither" ]; then
    variant nativeres_textured_read_f "UNTEXTURED READ_SUBTRACT READ_565" nativeres_color_read_subtract565_f
  fi
  # Untextured only: normal blending of alpha 0 (ReadWay::Invisible).
  variant nativeres_textured_read_f "UNTEXTURED READ_INVISIBLE $DITHER" nativeres_color_read_invisible${dither}_f
  variant nativeres_textured_read_f "UNTEXTURED READ_INVISIBLE READ_KEEP_ALPHA $DITHER" nativeres_color_read_invisiblekeep${dither}_f
done
# 8-bit targets (God of War): the GE's normal / additive blend without a cut
# (READ_WIDE, frame read; the target's alpha always kept: core frame.rs
# `wide_variant`), with and without fog and alpha test.
for way in normal add; do
  WAY=READ_$(echo $way | tr a-z A-Z)
  variant nativeres_textured_read_f "$WAY READ_WIDE READ_KEEP_ALPHA" nativeres_textured_read_${way}widekeep_f
  variant nativeres_textured_read_f "$WAY READ_WIDE READ_KEEP_ALPHA READ_TEST" nativeres_textured_read_${way}widekeeptest_f
  variant nativeres_textured_read_f "$WAY READ_WIDE READ_KEEP_ALPHA NO_FOG" nativeres_textured_read_${way}widekeepnofog_f
  variant nativeres_textured_read_f "$WAY READ_WIDE READ_KEEP_ALPHA NO_FOG READ_TEST" nativeres_textured_read_${way}widekeepnofogtest_f
  variant nativeres_textured_read_f "UNTEXTURED $WAY READ_WIDE READ_KEEP_ALPHA" nativeres_color_read_${way}widekeep_f
done
