#!/usr/bin/env python3
"""Packs the PSP-depth twins' compiled programs into one zlib-compressed
pack the plugin carries (vita/src/shaders.rs) and unpacks only when a game
needs them (`load_depth_pack`), so they take ~64 KB instead of ~250 KB in
the plugin's memory for every other game.

Writes vita/shaders/pspdepth.pak.z and vita/shaders/psp_depth_pack.rs (the
unpacked size and hash the plugin checks). Run by the build scripts before
cargo; both are checked in, so a plain cargo build has them.

Layout (little-endian u32s): "NRDP", version 1, entry count, FNV-1a hash of
everything after the header; then per entry its name (64 bytes, NUL-padded:
the twin's stem, e.g. nativeres_raw_pspdepth_v or nativeres_textured_pspwide_f), offset and size; then the
programs, each at a 16-byte boundary (GXM wants them aligned).
"""
import struct
import zlib
import sys
from pathlib import Path

shaders = Path(__file__).resolve().parent.parent / "vita" / "shaders"
NAME_BYTES = 64


def twin_names():
    names = []
    for line in (shaders / "psp_depth_twins.txt").read_text().splitlines():
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        stem, *defines = line.split()
        # As scripts/shader-variants.sh: nativeres_x_f -> nativeres_x_pspdepth_f,
        # the GE_FILTER ones also nativeres_x_pspwide_f (GE_WIDE) and
        # nativeres_x_pspgather_f (GE_GATHER).
        head, kind = stem.rsplit("_", 1)
        names.append(f"{head}_pspdepth_{kind}")
        if "GE_FILTER" in defines:
            names.append(f"{head}_pspwide_{kind}")
            names.append(f"{head}_pspgather_{kind}")
        # The same three without the PSP depth, for draws without depth test.
        if "NO_DEPTH" in defines:
            names.append(f"{head}_nodepth_{kind}")
            names.append(f"{head}_nodepthwide_{kind}")
            names.append(f"{head}_nodepthgather_{kind}")
    return names


def fnv1a(data):
    h = 0x811C9DC5
    for byte in data:
        h = ((h ^ byte) * 0x01000193) & 0xFFFFFFFF
    return h


def main():
    names = twin_names()
    table_bytes = len(names) * (NAME_BYTES + 8)
    offset = 16 + table_bytes
    table = bytearray()
    blobs = bytearray()
    for name in names:
        encoded = name.encode()
        if len(encoded) >= NAME_BYTES:
            sys.exit(f"pack-depth-twins: name too long: {name}")
        program = (shaders / f"{name}.gxp").read_bytes()
        padding = (-(offset + len(blobs))) % 16
        blobs += bytes(padding)
        table += encoded.ljust(NAME_BYTES, b"\0") + struct.pack("<II", offset + len(blobs), len(program))
        blobs += program
    body = bytes(table) + bytes(blobs)
    pack = b"NRDP" + struct.pack("<III", 1, len(names), fnv1a(body)) + body
    packed = zlib.compress(pack, 9)
    target = shaders / "pspdepth.pak.z"
    if not target.exists() or target.read_bytes() != packed:
        target.write_bytes(packed)
    rust = (
        "// GENERATED by scripts/pack-depth-twins.py from the PSP-depth twins' .gxp: do not edit.\n"
        f"/// FNV-1a hash of the unpacked depth pack after its header.\n"
        f"pub const DEPTH_PACK_HASH: u32 = 0x{fnv1a(body):08X};\n"
        f"/// The unpacked depth pack's size in bytes.\n"
        f"pub const DEPTH_PACK_BYTES: usize = {len(pack)};\n"
        f"/// Programs in it (psp_depth_twins.txt's lines).\n"
        f"pub const DEPTH_PACK_COUNT: usize = {len(names)};\n"
    )
    target = shaders / "psp_depth_pack.rs"
    if not target.exists() or target.read_text() != rust:
        target.write_text(rust)
    print(f"pack-depth-twins: {len(names)} programs, {len(pack)} bytes, {len(packed)} packed")


main()
